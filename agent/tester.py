"""Writes a standalone pytest file for a converted script and runs it.

The generated test runs the converted script, then compares each named
variable against the reference values that were saved from real MATLAB.
Results are read back via pytest's JUnit XML so the agent gets a structured
list of failures to feed into the retry prompt.
"""
from __future__ import annotations

import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

TEST_TEMPLATE = '''"""Auto-generated by matlab-to-python-agent.

Checks that {script} reproduces the numerical outputs saved from MATLAB
in {reference}. Run with:  pytest {test_name}
"""
import json
import os
import pathlib
import runpy

import matplotlib
matplotlib.use("Agg")  # headless: no windows during tests
import matplotlib.pyplot as plt
import numpy as np
import pytest

HERE = pathlib.Path(__file__).parent
SCRIPT = HERE / "{script}"
REFERENCE = {{k: v for k, v in json.loads((HERE / "{reference}").read_text()).items()
             if not k.startswith("x__")}}  # skip provenance fields
SPEC = json.loads(r\'\'\'{spec_json}\'\'\')
DEFAULT_TOL = {{"rtol": 1e-6, "atol": 1e-9}}


@pytest.fixture(scope="module")
def ns():
    """Run the converted script once and expose its global variables."""
    cwd = os.getcwd()
    os.chdir(HERE)  # output files (PNGs, ...) land next to the script
    plt.close("all")
    try:
        g = runpy.run_path(str(SCRIPT), run_name="__main__")
        g["__figures__"] = [plt.figure(n) for n in plt.get_fignums()]
        yield g
    finally:
        os.chdir(cwd)


def _arr(v):
    return np.squeeze(np.asarray(v, dtype=float))


@pytest.mark.parametrize("name", list(REFERENCE))
def test_output_matches_matlab(ns, name):
    assert name in ns, f"{{name}}: variable not defined by the converted script"
    expected, got = _arr(REFERENCE[name]), _arr(ns[name])
    assert got.shape == expected.shape, f"{{name}}: shape {{got.shape}} != MATLAB shape {{expected.shape}}"
    tol = SPEC.get("tolerances", {{}}).get(name, DEFAULT_TOL)
    err = float(np.max(np.abs(got - expected))) if expected.size else 0.0
    assert np.allclose(got, expected, rtol=tol["rtol"], atol=tol["atol"]), (
        f"{{name}}: max abs error {{err:.3e}} exceeds rtol={{tol['rtol']}}, atol={{tol['atol']}}; "
        f"first values got={{np.ravel(got)[:4]}} expected={{np.ravel(expected)[:4]}}")


@pytest.mark.parametrize("fname", SPEC.get("expected_files", []))
def test_output_file_created(ns, fname):
    assert (HERE / fname).exists(), f"expected output file {{fname}} was not written"


def test_figure_structure(ns):
    want = SPEC.get("figure_axes_lines")
    if want is None:
        pytest.skip("no figure checks for this sample")
    figs = ns["__figures__"]
    assert figs, "no matplotlib figure was created"
    got = [len(ax.lines) for ax in figs[-1].axes]
    assert got == want, f"lines per subplot {{got}} != expected {{want}}"
'''


@dataclass
class CheckResult:
    passed: bool
    n_tests: int = 0
    n_failed: int = 0
    failures: list[str] = field(default_factory=list)  # one line per failing check
    raw_output: str = ""

    def report(self, max_chars: int = 3000) -> str:
        """Compact failure summary for the retry prompt."""
        text = "\n".join(self.failures) or self.raw_output
        return text[:max_chars]


def write_test(out_dir: Path, name: str, spec: dict, reference_path: Path) -> Path:
    """Write test_<name>.py (and a copy of the reference) into out_dir."""
    ref_copy = out_dir / f"{name}_reference.json"
    ref_copy.write_text(reference_path.read_text(encoding="utf-8"), encoding="utf-8")
    test_path = out_dir / f"test_{name}.py"
    test_path.write_text(TEST_TEMPLATE.format(
        script=f"{name}.py", reference=ref_copy.name, test_name=test_path.name,
        spec_json=json.dumps(spec)), encoding="utf-8")
    return test_path


def run_test(test_path: Path, timeout: int = 120) -> CheckResult:
    """Run pytest on one generated test file and parse the JUnit XML result."""
    xml_path = test_path.with_suffix(".xml")
    xml_path.unlink(missing_ok=True)
    try:
        proc = subprocess.run(
            [sys.executable, "-m", "pytest", str(test_path), "-q", "-p", "no:cacheprovider",
             f"--junitxml={xml_path}"],
            capture_output=True, text=True, timeout=timeout, cwd=test_path.parent)
    except subprocess.TimeoutExpired:
        return CheckResult(False, failures=[f"timeout: script ran longer than {timeout}s"])
    output = proc.stdout + proc.stderr
    if not xml_path.exists():
        return CheckResult(False, failures=[output[-2000:]], raw_output=output)

    root = ET.parse(xml_path).getroot()
    failures, n = [], 0
    for case in root.iter("testcase"):
        if case.find("skipped") is not None:
            continue
        n += 1
        bad = case.find("failure") if case.find("failure") is not None else case.find("error")
        if bad is not None:
            msg = (bad.get("message") or "").strip().splitlines()
            first = msg[0] if msg else ""
            # Errors (e.g. the script crashed) carry the traceback in the body.
            if bad.tag == "error" or not first:
                body = (bad.text or "").strip().splitlines()
                first = " | ".join(body[-3:])
            failures.append(f"{case.get('name')}: {first}")
    # A crash in the fixture fails every test with the same error: dedupe it.
    unique = list(dict.fromkeys(f.split(": ", 1)[-1] for f in failures))
    if len(unique) == 1 and len(failures) > 1:
        failures = [f"all {len(failures)} tests: {unique[0]}"]
    n_failed = sum(1 for c in root.iter("testcase")
                   if c.find("failure") is not None or c.find("error") is not None)
    return CheckResult(n_failed == 0 and n > 0, n, n_failed, failures, output)


def run_smoke(script_path: Path, timeout: int = 120) -> CheckResult:
    """No reference available: just check the converted script runs."""
    try:
        proc = subprocess.run([sys.executable, script_path.name], capture_output=True, text=True,
                              timeout=timeout, cwd=script_path.parent,
                              env={**__import__("os").environ, "MPLBACKEND": "Agg"})
    except subprocess.TimeoutExpired:
        return CheckResult(False, 1, 1, [f"timeout after {timeout}s"])
    ok = proc.returncode == 0
    tail = (proc.stderr or proc.stdout).strip().splitlines()[-5:]
    return CheckResult(ok, 1, 0 if ok else 1, [] if ok else ["script crashed: " + " | ".join(tail)],
                      proc.stdout + proc.stderr)
